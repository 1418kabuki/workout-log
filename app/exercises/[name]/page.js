const ExerciseDetailPage = () => {
    const { name } = useParams()
    const router = useRouter()
    const decodedName = decodeURIComponent(name)

    const exercise = allExercises.find(ex => ex.name === decodedName)
    const tips = exerciseTips[decodedName] || []

    if (!exercise) {
        return (
            <div className="py-[5rem] text-center">
                <p className="text-[1.6rem] text-[#383c42]">種目が見つかりませんでした</p>
            </div>
        )
    }

    return (
        <div>
            {/* 戻るボタン */}
            <button
                onClick={() => router.back()}
                className="mb-[2rem] flex w-auto items-center gap-[0.6rem] border-0 bg-transparent p-0 text-[1.4rem] text-[#383c42]"
            >
                <ArrowLeft size={18} />
                種目一覧に戻る
            </button>

            {/* 種目名・説明 */}
            <div className="mb-[2.5rem]">
                <h1 className="mb-[0.8rem] text-[2.9rem] font-bold text-foreground">
                    {exercise.name}
                </h1>
                <p className="mb-[1rem] text-[1.3rem] text-[#383c42]">
                    対象部位：{exercise.target}
                </p>
                <p className="text-[1.5rem] leading-[1.8] text-[#383c42]">
                    {exercise.desc}
                </p>
            </div>

            {/* 画像 */}
            <Card className="mb-[2.5rem] h-[26rem] gap-0 overflow-hidden rounded-[1.6rem] bg-[#fafafa] p-0 shadow-md ring-0">
                <img
                    src={exercise.image || muscleImages[exercise.category]}
                    alt={exercise.name}
                    className="h-full w-full object-contain"
                />
            </Card>

            {/* この種目のコツ */}
            {tips.length > 0 && (
                <div>
                    <h2 className="mb-[1.5rem] text-[1.8rem] font-bold text-foreground">
                        この種目のコツ
                    </h2>
                    <div className="grid grid-cols-1 gap-[1.5rem] sm:grid-cols-3">
                        {tips.map((tip, i) => (
                            <Card key={i} className="gap-0 rounded-[1.6rem] p-[2rem] shadow-md ring-0">
                                <p className="mb-[0.6rem] text-[1.5rem] font-bold text-foreground">
                                    {tip.title}
                                </p>
                                <p className="text-[1.3rem] leading-[1.7] text-[#383c42]">
                                    {tip.desc}
                                </p>
                            </Card>
                        ))}
                    </div>
                </div>
            )}
        </div>
    )
}

export default ExerciseDetailPage
